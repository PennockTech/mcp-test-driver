# Vendor the official MCP schemas and conformance requirement lists into
# docs/specs/.  Re-run when a new spec revision ships, then update
# src/mcp_test_driver/versions.py and docs/mcp-feature-matrix.md to match.
#
# Files are fetched from raw.githubusercontent.com pinned to a commit SHA,
# so the vendored copy is reproducible.  modelcontextprotocol.io itself is
# not used: the spec repo is the source the site is built from.
#
# Usage: scripts/fetch-specs.sh [spec-repo-ref] [conformance-repo-ref]
#   Refs default to the current tip of each repo's main branch.

set -eu

SPEC_REPO=modelcontextprotocol/modelcontextprotocol
CONF_REPO=modelcontextprotocol/conformance

# Every dated revision, plus the rolling draft.  Add new revisions here.
VERSIONS="2024-11-05 2025-03-26 2025-06-18 2025-11-25 2026-07-28 draft"
# Conformance requirement lists exist only from 2025-11-25 onwards.
CONF_FILES="2025-11-25.yaml 2026-07-28.yaml"

die() { printf '%s: %s\n' "$0" "$*" >&2; exit 1; }

resolve_ref() {
  repo="$1" ref="$2"
  if printf '%s' "$ref" | grep -Eq '^[0-9a-f]{40}$'; then
    printf '%s\n' "$ref"
    return
  fi
  git ls-remote "https://github.com/$repo" "refs/heads/$ref" | cut -f1
}

fetch() {
  url="$1" dest="$2"
  mkdir -p "$(dirname "$dest")"
  curl -fsS --retry 3 --max-time 60 -o "$dest.tmp" "$url" || die "fetch failed: $url"
  mv "$dest.tmp" "$dest"
}

top="$(git rev-parse --show-toplevel)"
out="$top/docs/specs"

spec_sha="$(resolve_ref "$SPEC_REPO" "${1:-main}")"
conf_sha="$(resolve_ref "$CONF_REPO" "${2:-main}")"
[ -n "$spec_sha" ] || die "cannot resolve $SPEC_REPO ref"
[ -n "$conf_sha" ] || die "cannot resolve $CONF_REPO ref"

for v in $VERSIONS; do
  for f in schema.json schema.ts; do
    fetch "https://raw.githubusercontent.com/$SPEC_REPO/$spec_sha/schema/$v/$f" "$out/$v/$f"
  done
  # Changelogs give the human-readable diff between revisions.
  # 2024-11-05 is the first revision and has no changelog.
  if [ "$v" != 2024-11-05 ]; then
    fetch "https://raw.githubusercontent.com/$SPEC_REPO/$spec_sha/docs/specification/$v/changelog.mdx" \
      "$out/$v/changelog.mdx"
  fi
done

for f in $CONF_FILES; do
  fetch "https://raw.githubusercontent.com/$CONF_REPO/$conf_sha/requirements/$f" "$out/conformance/$f"
done

stamp="$out/SOURCES"
{
  printf '# Generated by scripts/fetch-specs.sh — do not edit.\n'
  printf 'fetched=%s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf 'spec_repo=https://github.com/%s\n' "$SPEC_REPO"
  printf 'spec_commit=%s\n' "$spec_sha"
  printf 'conformance_repo=https://github.com/%s\n' "$CONF_REPO"
  printf 'conformance_commit=%s\n' "$conf_sha"
  printf 'versions=%s\n' "$VERSIONS"
} >"$stamp"

printf 'Vendored %s into %s\n' "$VERSIONS" "$out"
